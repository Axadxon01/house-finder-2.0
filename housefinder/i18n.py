def lang() -> str:
    try:
        return st.session_state.get("lang", "uz")
    except Exception:  # outside a Streamlit run
        return "uz"


def t(key: str, **kwargs) -> str:
    entry = T.get(key)
    if entry is None:
        return key
    text = entry[_INDEX.get(lang(), 0)] or entry[1]
    return text.format(**kwargs) if kwargs else text
